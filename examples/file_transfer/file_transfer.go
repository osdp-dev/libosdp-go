/*
File Transfer Example

This example demonstrates OSDP file transfer capabilities:
- CP initiates file transfer to PD
- PD receives and stores the file
- Progress monitoring
- Error handling
- File operations interface implementation

Run this example with appropriate FIFO pairs.
*/

package main

import (
	"fmt"
	"io"
	"log"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"

	"github.com/osdp-dev/libosdp-go"
)

// File operations implementation for CP (sender)
type CPFileOps struct {
	files map[int]*os.File // Map of file ID to open file
}

func NewCPFileOps() *CPFileOps {
	return &CPFileOps{
		files: make(map[int]*os.File),
	}
}

func (f *CPFileOps) Open(fileID int) (size int, err error) {
	// For demo, use predefined files based on file ID
	var filename string
	switch fileID {
	case 1:
		filename = "test_config.txt"
	case 2:
		filename = "firmware.bin"
	default:
		return 0, fmt.Errorf("unsupported file ID: %d", fileID)
	}

	// Create test file if it doesn't exist
	if _, err := os.Stat(filename); os.IsNotExist(err) {
		if err := f.createTestFile(filename, fileID); err != nil {
			return 0, fmt.Errorf("failed to create test file: %v", err)
		}
	}

	file, err := os.Open(filename)
	if err != nil {
		return 0, fmt.Errorf("failed to open file %s: %v", filename, err)
	}

	stat, err := file.Stat()
	if err != nil {
		file.Close()
		return 0, fmt.Errorf("failed to get file stats: %v", err)
	}

	f.files[fileID] = file
	fmt.Printf("CP: Opened file %s (ID: %d, Size: %d bytes)\n", filename, fileID, stat.Size())
	return int(stat.Size()), nil
}

func (f *CPFileOps) Read(buffer []byte, size int, offset int) (bytesRead int, err error) {
	// Find the file (assume only one file is open at a time for simplicity)
	var file *os.File
	for _, f := range f.files {
		file = f
		break
	}

	if file == nil {
		return 0, fmt.Errorf("no file is open")
	}

	_, err = file.Seek(int64(offset), io.SeekStart)
	if err != nil {
		return 0, fmt.Errorf("failed to seek: %v", err)
	}

	n, err := file.Read(buffer[:size])
	if err != nil && err != io.EOF {
		return 0, fmt.Errorf("failed to read: %v", err)
	}

	fmt.Printf("CP: Read %d bytes at offset %d\n", n, offset)
	return n, nil
}

func (f *CPFileOps) Write(buffer []byte, size int, offset int) (bytesWritten int, err error) {
	return 0, fmt.Errorf("CP does not support write operations")
}

func (f *CPFileOps) Close() error {
	for fileID, file := range f.files {
		file.Close()
		delete(f.files, fileID)
		fmt.Printf("CP: Closed file ID %d\n", fileID)
	}
	return nil
}

func (f *CPFileOps) createTestFile(filename string, fileID int) error {
	file, err := os.Create(filename)
	if err != nil {
		return err
	}
	defer file.Close()

	switch fileID {
	case 1:
		// Create a config file
		content := `# OSDP Configuration File
device_name=Test_Device
baud_rate=115200
secure_channel=enabled
led_count=2
output_count=4
# Generated by OSDP Go Example
timestamp=` + time.Now().Format(time.RFC3339) + `
`
		file.WriteString(content)
	case 2:
		// Create a binary file (simulated firmware)
		data := make([]byte, 1024)
		for i := range data {
			data[i] = byte(i % 256)
		}
		file.Write(data)
	}

	return nil
}

// File operations implementation for PD (receiver)
type PDFileOps struct {
	files       map[int]*os.File
	filenames   map[int]string
	receivedDir string
}

func NewPDFileOps() *PDFileOps {
	receivedDir := "received_files"
	os.MkdirAll(receivedDir, 0755)

	return &PDFileOps{
		files:       make(map[int]*os.File),
		filenames:   make(map[int]string),
		receivedDir: receivedDir,
	}
}

func (f *PDFileOps) Open(fileID int) (size int, err error) {
	// Determine filename based on file ID
	var filename string
	switch fileID {
	case 1:
		filename = "received_config.txt"
	case 2:
		filename = "received_firmware.bin"
	default:
		return 0, fmt.Errorf("unsupported file ID: %d", fileID)
	}

	fullPath := filepath.Join(f.receivedDir, filename)
	file, err := os.Create(fullPath)
	if err != nil {
		return 0, fmt.Errorf("failed to create file %s: %v", fullPath, err)
	}

	f.files[fileID] = file
	f.filenames[fileID] = fullPath
	fmt.Printf("PD: Created file %s for receiving (ID: %d)\n", fullPath, fileID)
	return 0, nil // Size will be determined by incoming data
}

func (f *PDFileOps) Read(buffer []byte, size int, offset int) (bytesRead int, err error) {
	return 0, fmt.Errorf("PD does not support read operations during transfer")
}

func (f *PDFileOps) Write(buffer []byte, size int, offset int) (bytesWritten int, err error) {
	// Find the file (assume only one file is open at a time for simplicity)
	var file *os.File
	var fileID int
	for id, f := range f.files {
		file = f
		fileID = id
		break
	}

	if file == nil {
		return 0, fmt.Errorf("no file is open")
	}

	_, err = file.Seek(int64(offset), io.SeekStart)
	if err != nil {
		return 0, fmt.Errorf("failed to seek: %v", err)
	}

	n, err := file.Write(buffer[:size])
	if err != nil {
		return 0, fmt.Errorf("failed to write: %v", err)
	}

	fmt.Printf("PD: Wrote %d bytes at offset %d to file ID %d\n", n, offset, fileID)
	return n, nil
}

func (f *PDFileOps) Close() error {
	for fileID, file := range f.files {
		file.Close()
		filename := f.filenames[fileID]

		// Get file size for confirmation
		if stat, err := os.Stat(filename); err == nil {
			fmt.Printf("PD: File transfer completed - %s (%d bytes)\n", filename, stat.Size())
		}

		delete(f.files, fileID)
		delete(f.filenames, fileID)
	}
	return nil
}

func main() {
	if len(os.Args) < 5 {
		fmt.Printf("Usage: %s <mode> <rx_fifo> <tx_fifo> <file_id>\n", os.Args[0])
		fmt.Println("  mode: 'cp' for Control Panel (sender) or 'pd' for Peripheral Device (receiver)")
		fmt.Println("  file_id: 1 for config file, 2 for firmware file")
		fmt.Println("\nExample:")
		fmt.Println("  # Terminal 1 (PD - receiver)")
		fmt.Printf("  %s pd /tmp/pd_tx.fifo /tmp/pd_rx.fifo 1\n", os.Args[0])
		fmt.Println("  # Terminal 2 (CP - sender)")
		fmt.Printf("  %s cp /tmp/pd_rx.fifo /tmp/pd_tx.fifo 1\n", os.Args[0])
		os.Exit(1)
	}

	mode := os.Args[1]
	rxFifo := os.Args[2]
	txFifo := os.Args[3]
	fileID := 1
	if len(os.Args) >= 5 {
		fmt.Sscanf(os.Args[4], "%d", &fileID)
	}

	// Create FIFO channel
	channel, err := osdp.NewFIFOChannel(rxFifo, txFifo)
	if err != nil {
		log.Fatalf("Failed to create FIFO channel: %v", err)
	}
	defer channel.Close()

	// Handle graceful shutdown
	sigChan := make(chan os.Signal, 1)
	signal.Notify(sigChan, syscall.SIGINT, syscall.SIGTERM)

	if mode == "cp" {
		runCP(channel, fileID, sigChan)
	} else if mode == "pd" {
		runPD(channel, fileID, sigChan)
	} else {
		log.Fatalf("Invalid mode: %s. Use 'cp' or 'pd'", mode)
	}
}

func runCP(channel *osdp.FIFOChannel, fileID int, sigChan chan os.Signal) {
	fmt.Println("Starting Control Panel (File Sender)...")

	// Create file operations
	fileOps := NewCPFileOps()

	// Event handler
	eventHandler := func(pdNumber int, event *osdp.Event) int {
		fmt.Printf("CP: Received event type %d from PD %d\n", event.Event.GetType(), pdNumber)
		return 0
	}

	// Create PD info
	pdInfo := &osdp.PdInfo{
		Address:  1,
		BaudRate: 9600,
		Flags:    osdp.FlagInstallMode,
		ID: osdp.PdId{
			Version: 1, Model: 1, VendorCode: 0x153, SerialNumber: 0x12345,
		},
	}

	// Create CP
	cp, err := osdp.NewControlPanel(channel, []*osdp.PdInfo{pdInfo}, osdp.LogInfo)
	if err != nil {
		log.Fatalf("Failed to create CP: %v", err)
	}
	defer cp.Stop()

	// Set event handler after creation
	err = cp.SetEventHandler(eventHandler)
	if err != nil {
		log.Fatalf("Failed to set event handler: %v", err)
	}

	// Register file operations
	if err := cp.RegisterFileOperations(0, fileOps); err != nil {
		log.Fatalf("Failed to register file operations: %v", err)
	}

	fmt.Printf("CP: Registered file operations, waiting for PD connection...\n")

	// Wait for PD to come online
	fmt.Println("Waiting for PD to come online...")
	for {
		online, _ := cp.IsOnline(0)
		if online {
			fmt.Println("PD is online")
			break
		}
		time.Sleep(1 * time.Second)
	}

	// Start file transfer
	fmt.Printf("Initiating file transfer (File ID: %d)...\n", fileID)
	fileTxCmd := &osdp.Command{
		Command: osdp.CommandFileTx{
			ID:    int32(fileID),
			Flags: 0,
		},
	}

	if err := cp.SubmitCommand(0, fileTxCmd); err != nil {
		log.Fatalf("Failed to send file transfer command: %v", err)
	}

	fmt.Println("File transfer command sent. Monitoring progress...")

	// Monitor transfer progress
	ticker := time.NewTicker(2 * time.Second)
	defer ticker.Stop()

	for {
		select {
		case <-sigChan:
			fmt.Println("\nReceived shutdown signal, stopping...")
			return

		case <-ticker.C:
			if status, err := cp.GetFileTransferStatus(0); err == nil {
				if status.Size > 0 {
					progress := float64(status.Offset) / float64(status.Size) * 100
					fmt.Printf("Transfer progress: %d/%d bytes (%.1f%%)\n",
						status.Offset, status.Size, progress)

					if status.Offset >= status.Size {
						fmt.Println("File transfer completed successfully!")
						time.Sleep(2 * time.Second)
						return
					}
				}
			} else {
				fmt.Printf("Failed to get transfer status: %v\n", err)
			}
		}
	}
}

func runPD(channel *osdp.FIFOChannel, fileID int, sigChan chan os.Signal) {
	fmt.Println("Starting Peripheral Device (File Receiver)...")

	// Create file operations
	fileOps := NewPDFileOps()
	defer fileOps.Close()

	// Command handler
	commandHandler := func(command *osdp.Command) (int, *osdp.Event) {
		switch command.Command.GetType() {
		case osdp.CmdFileTx:
			fmt.Printf("PD: Received file transfer command\n")
		default:
			fmt.Printf("PD: Received command type %d\n", command.Command.GetType())
		}
		return 0, nil // ACK
	}

	// Create PD info
	pdInfo := &osdp.PdInfo{
		Address:  1,
		BaudRate: 9600,
		Flags:    osdp.FlagInstallMode,
		ID: osdp.PdId{
			Version: 1, Model: 1, VendorCode: 0x153, SerialNumber: 0x12345,
			FirmwareMajor: 1, FirmwareMinor: 0, FirmwareBuild: 1,
		},
	}

	// Create capabilities
	capabilities := []osdp.PdCapability{
		{Function: osdp.CapReaderLEDControl, Compliance: 1, NumItems: 1},
	}

	// Create PD
	pd, err := osdp.NewPeripheralDevice(channel, pdInfo, capabilities, osdp.LogInfo)
	if err != nil {
		log.Fatalf("Failed to create PD: %v", err)
	}

	// Set command handler after creation
	err = pd.SetCommandHandler(commandHandler)
	if err != nil {
		log.Fatalf("Failed to set command handler: %v", err)
	}
	defer pd.Stop()

	// Register file operations
	if err := pd.RegisterFileOperations(fileOps); err != nil {
		log.Fatalf("Failed to register file operations: %v", err)
	}

	fmt.Printf("PD: Ready to receive files. File operations registered.\n")
	fmt.Println("Waiting for file transfer commands from CP...")

	// Monitor transfer progress
	ticker := time.NewTicker(3 * time.Second)
	defer ticker.Stop()

	for {
		select {
		case <-sigChan:
			fmt.Println("\nReceived shutdown signal, stopping...")
			return

		case <-ticker.C:
			if status, err := pd.GetFileTransferStatus(); err == nil {
				if status.Size > 0 {
					progress := float64(status.Offset) / float64(status.Size) * 100
					fmt.Printf("Receive progress: %d/%d bytes (%.1f%%)\n",
						status.Offset, status.Size, progress)

					if status.Offset >= status.Size {
						fmt.Println("File received successfully!")
						// Continue running to allow more transfers
					}
				}
			}
		}
	}
}
